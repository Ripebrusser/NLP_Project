#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Machine-checkable validation of the final literature comparison workbook.

The workbook is generated by ``build_final_lit_matrix.py``. This module checks
it against the authoritative verification register
(``Admin/LITERATURE_VERIFICATION_REGISTER.md``) instead of trusting the builder's
own printout, so a dropped or reclassified reference cannot pass silently.

Run:
    .venv/Scripts/python.exe "Research Work/validate_literature_matrix.py"
Exit status is 0 only when every check passes.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pandas as pd
from openpyxl import load_workbook

BASE = Path(__file__).resolve().parents[1]
REGISTER = BASE / "Admin" / "LITERATURE_VERIFICATION_REGISTER.md"
XLSX = BASE / "Admin" / "FINAL_LITERATURE_COMPARISON_MATRIX.xlsx"
CSV = BASE / "Literature Review" / "FINAL_LITERATURE_COMPARISON_MATRIX.csv"

ACCESS_TO_VERIFICATION = {
    "FULL": "FULL TEXT",
    "ABSTRACT": "ABSTRACT",
    "METADATA": "METADATA",
    "EXCLUDED": "EXCLUDED",
}
# Audited snapshot: 7 + 6 + 10 + 1 = 24. The register's prose summary used to
# say "(9)" while listing ten METADATA records; the table and workbook agree on
# ten, and the prose was corrected on 8 November 2026.
EXPECTED_COUNTS = {"FULL TEXT": 7, "ABSTRACT": 6, "METADATA": 10, "EXCLUDED": 1}
ALLOWED_NO_NUMBER = (
    "do not cite", "no numerical result", "no numeric", "no count used",
    "no confirmable", "no result extracted", "not verified",
)
NUMBER_RE = re.compile(r"\d+\.\d+")


class LiteratureValidationError(ValueError):
    """Raised when the workbook disagrees with the verification register."""


def parse_register(path: Path = REGISTER) -> pd.DataFrame:
    """Read the register's verification table into ``id``/``access`` columns."""
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0] in {"ID", "---"} or set(cells[0]) <= {"-", ":"}:
            continue
        paper_id = cells[0]
        if not re.fullmatch(r"[A-Z]\d{2}", paper_id):
            continue
        access = cells[2].replace("*", "").strip().upper()
        if access not in ACCESS_TO_VERIFICATION:
            raise LiteratureValidationError(
                f"{paper_id}: unrecognised register access level {access!r}"
            )
        rows.append({"id": paper_id, "access": access})
    frame = pd.DataFrame(rows)
    if frame.empty:
        raise LiteratureValidationError(f"No register rows parsed from {path}")
    return frame


def load_workbook_rows(path: Path = XLSX) -> pd.DataFrame:
    return pd.read_excel(path, sheet_name="Paper Matrix", dtype=str).fillna("")


def _check(condition: bool, message: str, failures: list[str]) -> None:
    if not condition:
        failures.append(message)


def validate(
    register_path: Path = REGISTER,
    xlsx_path: Path = XLSX,
    csv_path: Path = CSV,
) -> dict:
    """Validate workbook, CSV and register agreement. Raises on any failure."""
    failures: list[str] = []
    register = parse_register(register_path)
    book = load_workbook_rows(xlsx_path)

    _check(register["id"].is_unique, "register contains duplicate IDs", failures)
    _check(book["ID"].is_unique, "workbook contains duplicate IDs", failures)
    _check(len(register) == 24, f"register has {len(register)} records, expected 24",
           failures)

    missing = sorted(set(register["id"]) - set(book["ID"]))
    extra = sorted(set(book["ID"]) - set(register["id"]))
    _check(not missing, f"workbook is missing register IDs: {missing}", failures)
    _check(not extra, f"workbook has IDs absent from the register: {extra}", failures)

    merged = register.merge(book, left_on="id", right_on="ID", how="inner")
    mismatches = []
    for _, row in merged.iterrows():
        expected = ACCESS_TO_VERIFICATION[row["access"]]
        if str(row["Verification"]).strip().upper() != expected:
            mismatches.append(
                f"{row['id']}: workbook says {row['Verification']!r}, "
                f"register says {expected!r}"
            )
    _check(not mismatches, "; ".join(mismatches), failures)

    counts = book["Verification"].value_counts().to_dict()
    register_counts = {ACCESS_TO_VERIFICATION[k]: int(v)
                       for k, v in register["access"].value_counts().items()}
    for level, expected in register_counts.items():
        _check(counts.get(level, 0) == expected,
               f"{level}: workbook has {counts.get(level, 0)}, register has {expected}",
               failures)
    for level, expected in EXPECTED_COUNTS.items():
        _check(counts.get(level, 0) == expected,
               f"{level}: workbook has {counts.get(level, 0)}, expected {expected}",
               failures)
    active = int((book["Verification"] != "EXCLUDED").sum())
    _check(active == 23, f"active (citable) records = {active}, expected 23", failures)

    excluded = book[book["Verification"] == "EXCLUDED"]
    for _, row in excluded.iterrows():
        text = f"{row['Relevance']} {row['Verified results']}".lower()
        _check("excluded" in text or "do not cite" in text,
               f"{row['ID']}: EXCLUDED record does not say so in Relevance/Results",
               failures)

    # A non-full-text record must not carry a bare decimal result. Quoting a
    # number only inside an explicit "do not cite" warning is allowed.
    numeric_leaks = []
    for _, row in book[book["Verification"] != "FULL TEXT"].iterrows():
        cell = str(row["Verified results"])
        if NUMBER_RE.search(cell):
            lowered = cell.strip().lower()
            if not lowered.startswith(ALLOWED_NO_NUMBER):
                numeric_leaks.append(f"{row['ID']}: {cell[:80]!r}")
    _check(not numeric_leaks,
           "unverified records carry numeric results without a 'do not cite' "
           f"marker: {numeric_leaks}", failures)

    if csv_path.exists():
        csv_rows = pd.read_csv(csv_path, encoding="utf-8-sig", dtype=str).fillna("")
        _check(list(csv_rows.columns) == list(book.columns),
               "CSV columns differ from workbook columns", failures)
        _check(len(csv_rows) == len(book),
               f"CSV has {len(csv_rows)} rows, workbook has {len(book)}", failures)
        if list(csv_rows.columns) == list(book.columns) and len(csv_rows) == len(book):
            a = book.sort_values("ID").reset_index(drop=True)
            b = csv_rows.sort_values("ID").reset_index(drop=True)
            same = a.astype(str).equals(b.astype(str))
            _check(same, "CSV content differs from the workbook", failures)
    else:
        failures.append(f"CSV not found: {csv_path}")

    wb = load_workbook(xlsx_path)
    _check(wb.sheetnames == ["Paper Matrix", "Verification Summary"],
           f"unexpected sheet names: {wb.sheetnames}", failures)
    sheet = wb["Paper Matrix"]
    _check(sheet.freeze_panes == "A2",
           f"Paper Matrix freeze panes = {sheet.freeze_panes!r}, expected 'A2'",
           failures)
    _check(sheet.auto_filter.ref is not None, "Paper Matrix has no auto-filter",
           failures)
    summary = pd.read_excel(xlsx_path, sheet_name="Verification Summary")
    summary_counts = dict(zip(summary["Verification"], summary["Count"]))
    for level, expected in EXPECTED_COUNTS.items():
        _check(int(summary_counts.get(level, 0)) == expected,
               f"summary sheet {level} = {summary_counts.get(level)}, "
               f"expected {expected}", failures)

    # The on-disk workbook must still equal the builder's declared rows, so a
    # hand edit that quietly drops or reclassifies a reference is visible.
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from build_final_lit_matrix import COLS, ROWS  # noqa: E402

    declared = pd.DataFrame(ROWS, columns=COLS).astype(str)
    on_disk = book.astype(str)
    _check(len(declared) == len(on_disk),
           f"builder declares {len(declared)} rows, workbook has {len(on_disk)}",
           failures)
    if len(declared) == len(on_disk):
        same_as_builder = declared.sort_values("ID").reset_index(drop=True).equals(
            on_disk.sort_values("ID").reset_index(drop=True))
        _check(same_as_builder,
               "workbook content differs from build_final_lit_matrix.ROWS", failures)

    result = {
        "status": "PASS" if not failures else "FAIL",
        "records_register": int(len(register)),
        "records_workbook": int(len(book)),
        "active_records": active,
        "verification_counts": counts,
        "expected_counts": EXPECTED_COUNTS,
        "failures": failures,
    }
    if failures:
        raise LiteratureValidationError(json.dumps(result, indent=2, ensure_ascii=False))
    return result


def main() -> int:
    try:
        result = validate()
    except LiteratureValidationError as exc:
        print("LITERATURE MATRIX VALIDATION: FAIL")
        print(exc)
        return 1
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
